class PriceProductionHistoryScreen(Screen):
    selected_crop_id = None
    selected_crop_name = StringProperty()
    selected_date = None
    selected_date_str = StringProperty()
    inspect_mode = StringProperty("ai_forecast")  # "ai_forecast" or "historical_actual"
    selected_year = NumericProperty(2025)
    trend_metric = StringProperty("price")  # "price" or "production"
    _menu = None
    crops = []
    available_years = []

    def on_pre_enter(self, *args):
        # Pre-populate crops if not loaded
        if not self.crops:
            self.crops = [(cid, name) for cid, name in get_all_crops()]
        if self.crops and not self.selected_crop_id:
            self.selected_crop_id, self.selected_crop_name = self.crops[0]
            if hasattr(self.ids, "crop_btn"):
                self.ids.crop_btn.text = self.selected_crop_name

        if self.inspect_mode == "ai_forecast":
            if not self.selected_date or self.selected_date < date.today():
                self.selected_date = date.today() + timedelta(days=7)
                self.selected_date_str = self.selected_date.strftime("%d %b %Y")
        else:
            latest_dt = get_latest_record_date(self.selected_crop_id) or (date.today() - timedelta(days=1))
            if not self.selected_date or self.selected_date >= date.today():
                self.selected_date = latest_dt
                self.selected_date_str = latest_dt.strftime("%d %b %Y")

        if hasattr(self.ids, "date_btn"):
            self.ids.date_btn.text = self.selected_date_str
        self.set_inspect_mode(self.inspect_mode)
        self.build_year_chips()
        self.render_trend_chart()


    def set_inspect_mode(self, mode):
        self.inspect_mode = mode
        if mode == "ai_forecast":
            if hasattr(self.ids, "tab_ai_btn"):
                self.ids.tab_ai_btn.md_bg_color = (0.25, 0.62, 0.30, 1)
                self.ids.tab_ai_btn.text_color = (1, 1, 1, 1)
            if hasattr(self.ids, "tab_hist_btn"):
                self.ids.tab_hist_btn.md_bg_color = (0.92, 0.95, 0.92, 1)
                self.ids.tab_hist_btn.text_color = (0.2, 0.45, 0.2, 1)
            if hasattr(self.ids, "mode_desc_lbl"):
                self.ids.mode_desc_lbl.text = "Select any future date from today onwards to inspect AI forecasts."
            if hasattr(self.ids, "search_action_btn"):
                self.ids.search_action_btn.text = "GENERATE AI PREDICTION"

            # Set default future date if in past
            if not self.selected_date or self.selected_date < date.today():
                self.selected_date = date.today() + timedelta(days=7)
                self.selected_date_str = self.selected_date.strftime("%d %b %Y")
                if hasattr(self.ids, "date_btn"):
                    self.ids.date_btn.text = self.selected_date_str

            if hasattr(self.ids, "actual_card"):
                self.ids.actual_card.opacity = 0
                self.ids.actual_card.height = 0
                self.ids.actual_card.disabled = True
            if hasattr(self.ids, "pred_card"):
                self.ids.pred_card.opacity = 1
                self.ids.pred_card.height = self.ids.pred_card.minimum_height
                self.ids.pred_card.disabled = False
        else:
            if hasattr(self.ids, "tab_ai_btn"):
                self.ids.tab_ai_btn.md_bg_color = (0.92, 0.95, 0.92, 1)
                self.ids.tab_ai_btn.text_color = (0.2, 0.45, 0.2, 1)
            if hasattr(self.ids, "tab_hist_btn"):
                self.ids.tab_hist_btn.md_bg_color = (0.25, 0.62, 0.30, 1)
                self.ids.tab_hist_btn.text_color = (1, 1, 1, 1)
            if hasattr(self.ids, "mode_desc_lbl"):
                self.ids.mode_desc_lbl.text = "Select dates within verified past records to view actual market prices & production."
            if hasattr(self.ids, "search_action_btn"):
                self.ids.search_action_btn.text = "LOAD HISTORICAL DATA"

            latest_dt = get_latest_record_date(self.selected_crop_id) or (date.today() - timedelta(days=1))
            if not self.selected_date or self.selected_date >= date.today():
                self.selected_date = latest_dt
                self.selected_date_str = latest_dt.strftime("%d %b %Y")
                if hasattr(self.ids, "date_btn"):
                    self.ids.date_btn.text = self.selected_date_str

            if hasattr(self.ids, "actual_card"):
                self.ids.actual_card.opacity = 1
                self.ids.actual_card.height = self.ids.actual_card.minimum_height
                self.ids.actual_card.disabled = False
            if hasattr(self.ids, "pred_card"):
                self.ids.pred_card.opacity = 0
                self.ids.pred_card.height = 0
                self.ids.pred_card.disabled = True

        self.load_data()

    def go_back(self):
        if self.manager:
            self.manager.transition.direction = "right"
            self.manager.current = "dashboard"

    def open_crop_menu(self):
        if not self.crops:
            self.crops = [(cid, name) for cid, name in get_all_crops()]
        menu_items = [
            {
                "viewclass": "OneLineListItem",
                "text": name,
                "height": dp(48),
                "on_release": lambda y=cid, x=name: self.select_crop(y, x),
            }
            for cid, name in self.crops
        ]
        if self._menu:
            self._menu.dismiss()
        self._menu = MDDropdownMenu(
            caller=self.ids.crop_btn,
            items=menu_items,
            width_mult=4,
        )
        self._menu.open()

    def select_crop(self, crop_id, crop_name):
        self.selected_crop_id = crop_id
        self.selected_crop_name = crop_name
        if hasattr(self.ids, "crop_btn"):
            self.ids.crop_btn.text = crop_name
        if self._menu:
            self._menu.dismiss()
        self.load_data()
        self.build_year_chips()
        self.render_trend_chart()


    def show_date_picker(self):
        try:
            if self.inspect_mode == "ai_forecast":
                min_d = date.today()
                max_d = date.today() + timedelta(days=365)
                init_d = self.selected_date if (self.selected_date and self.selected_date >= min_d) else (date.today() + timedelta(days=7))
                picker = MDDatePicker(
                    min_date=min_d,
                    max_date=max_d,
                    year=init_d.year,
                    month=init_d.month,
                    day=init_d.day,
                )
            else:
                latest_dt = get_latest_record_date(self.selected_crop_id) or (date.today() - timedelta(days=1))
                earliest_dt = get_earliest_record_date(self.selected_crop_id) or date(2020, 1, 1)
                init_d = self.selected_date if (self.selected_date and earliest_dt <= self.selected_date <= latest_dt) else latest_dt
                picker = MDDatePicker(
                    min_date=earliest_dt,
                    max_date=latest_dt,
                    year=init_d.year,
                    month=init_d.month,
                    day=init_d.day,
                )
            picker.bind(on_save=self.on_date_selected)
            picker.open()
        except Exception as e:
            print(f"[PriceHistoryScreen] DatePicker error: {e}")

    def on_date_selected(self, instance, value, date_range):
        self.selected_date = value
        self.selected_date_str = value.strftime("%d %b %Y")
        if hasattr(self.ids, "date_btn"):
            self.ids.date_btn.text = self.selected_date_str
        self.load_data()

    def load_data(self):
        if not self.selected_crop_id:
            show_snackbar("Please select a crop first.")
            return
        if not self.selected_date:
            show_snackbar("Please select a date first.")
            return

        app = MDApp.get_running_app()
        region_id = app.current_user.get("region_id") if (app and app.current_user) else None
        district = (get_region_district(region_id) if region_id else None) or "Kandy"

        if self.inspect_mode == "ai_forecast":
            self.ids.pred_district_lbl.text = f"Forecast Region: {district}  •  Crop: {self.selected_crop_name}  •  Target: {self.selected_date_str}"
            hist_rows = get_price_history(self.selected_crop_id, region_id=region_id, weeks=14)
            p_history = [p for _, p in hist_rows] if hist_rows else None
            curr_p = p_history[-1] if p_history else 200.0
            pred_price = predict_price(crop=self.selected_crop_name, district=district, price_history=p_history, current_price=curr_p)
            pred_prod = predict_production(vegetable=self.selected_crop_name, district=district)

            if pred_price is not None:
                self.ids.pred_price_label.text = f"Rs. {pred_price:,.2f} / kg"
            else:
                self.ids.pred_price_label.text = "Prediction unavailable"

            if pred_prod is not None:
                self.ids.pred_prod_label.text = f"{pred_prod:,.2f} Mt"
            else:
                self.ids.pred_prod_label.text = "Prediction unavailable"
        else:
            self.ids.actual_date_lbl.text = f"Recorded Date: {self.selected_date_str}  •  Crop: {self.selected_crop_name}  •  Region: {district}"
            price = get_price_by_date(self.selected_crop_id, self.selected_date, region_id=region_id)
            prod = get_production_by_date(self.selected_crop_id, self.selected_date, region_id=region_id)

            if price is not None:
                self.ids.actual_price_label.text = f"Rs. {price:,.2f} / kg"
                self.ids.actual_price_label.text_color = (0.15, 0.45, 0.20, 1)
            else:
                self.ids.actual_price_label.text = "No price recorded for this date"
                self.ids.actual_price_label.text_color = (0.6, 0.4, 0.2, 1)

            if prod is not None:
                self.ids.actual_prod_label.text = f"{prod:,.2f} Mt"
                self.ids.actual_prod_label.text_color = (0.15, 0.45, 0.20, 1)
            else:
                self.ids.actual_prod_label.text = "No production recorded for this date"
                self.ids.actual_prod_label.text_color = (0.6, 0.4, 0.2, 1)

    def build_year_chips(self):
        if not hasattr(self.ids, "year_chips_box"):
            return
        box = self.ids.year_chips_box
        box.clear_widgets()

        years = get_available_record_years(self.selected_crop_id)
        if not years:
            years = [2025, 2024, 2023, 2022, 2021]
        self.available_years = years

        if self.selected_year not in years:
            self.selected_year = years[0]

        for yr in years:
            is_active = (yr == self.selected_year)
            btn = MDRaisedButton(
                text=str(yr),
                size_hint=(None, None),
                height=dp(32),
                elevation=0,
                _radius=10,
                md_bg_color=(0.22, 0.55, 0.25, 1) if is_active else (0.92, 0.95, 0.92, 1),
                text_color=(1, 1, 1, 1) if is_active else (0.20, 0.45, 0.20, 1),
                font_size="13sp",
                on_release=lambda x, y=yr: self.select_year(y),
            )
            box.add_widget(btn)

    def select_year(self, year):
        self.selected_year = int(year)
        self.build_year_chips()
        self.render_trend_chart()

