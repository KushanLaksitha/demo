    def render_trend_chart(self):
        if not hasattr(self.ids, "chart_container"):
            return
        container = self.ids.chart_container
        container.clear_widgets()

        if not self.selected_crop_id:
            return

        app = MDApp.get_running_app()
        region_id = app.current_user.get("region_id") if (app and app.current_user) else None
        district = (get_region_district(region_id) if region_id else None) or "Kandy"

        if self.trend_metric == "price":
            data, stats = get_price_history_by_year(self.selected_crop_id, self.selected_year, region_id=region_id)
            if not data:
                lbl = MDLabel(
                    text=f"No price data recorded for {self.selected_crop_name} in {self.selected_year}.",
                    halign="center",
                    theme_text_color="Custom",
                    text_color=(0.5, 0.5, 0.5, 1),
                )
                container.add_widget(lbl)
                return

            dates, values = zip(*data)
            chart = build_line_chart(
                list(dates), list(values),
                title=f"{self.selected_crop_name} — {self.selected_year} Price Trend ({district})",
                y_label="LKR / kg",
            )
            if stats and hasattr(self.ids, "stat_avg_lbl"):
                self.ids.stat_avg_lbl.text = f"Rs. {stats['avg']:,.1f}"
                self.ids.stat_peak_lbl.text = f"Rs. {stats['max']:,.0f} ({stats['max_month']})"
                self.ids.stat_floor_lbl.text = f"Rs. {stats['min']:,.0f} ({stats['min_month']})"
        else:
            data, stats = get_production_history_by_year(self.selected_crop_id, self.selected_year, region_id=region_id)
            if not data:
                lbl = MDLabel(
                    text=f"No production data recorded for {self.selected_crop_name} in {self.selected_year}.",
                    halign="center",
                    theme_text_color="Custom",
                    text_color=(0.5, 0.5, 0.5, 1),
                )
                container.add_widget(lbl)
                return

            dates, values = zip(*data)
            chart = build_bar_chart(
                list(dates), list(values),
                title=f"{self.selected_crop_name} — {self.selected_year} Harvest Volume ({district})",
                y_label="Mt",
            )
            if stats and hasattr(self.ids, "stat_avg_lbl"):
                self.ids.stat_avg_lbl.text = f"{stats['total']:,.0f} Mt Total"
                self.ids.stat_peak_lbl.text = f"{stats['max']:,.0f} Mt ({stats['max_month']})"
                self.ids.stat_floor_lbl.text = f"{stats['min']:,.0f} Mt ({stats['min_month']})"

        chart.size_hint = (1, 1)
        container.add_widget(chart)

